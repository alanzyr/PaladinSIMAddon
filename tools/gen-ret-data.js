// Writes the addon's copy of the website's data and the exact results its self-test compares with:
//   RetSim/Data.lua      default settings, base stats per race, the talents and the ready builds
//   RetSim/Expected.lua  a few fights played by the website's engine
// Run it again whenever ret-sim.html changes:   node gen-ret-data.js
const fs = require('fs'), path = require('path');
const { toLua } = require('./lua-ser');
const JS = require('./ret-js-engine');
const page = fs.readFileSync(JS.file, 'utf8').replace(/\r\n/g, '\n');
const VERSION = fs.readFileSync(path.join(__dirname, '..', 'RetSim', 'RetSim.toc'), 'utf8').match(/## Version: *(\S+)/)[1];

const ra = page.indexOf('const RACE_BASE = '), rb = page.indexOf(';\n', ra);
const RACE_BASE = new Function('return ' + page.slice(ra + 18, rb))();
const ta = page.indexOf('const TREES'), tb = page.indexOf('\n];', ta);
const TREES = new Function('return ' + page.slice(ta + 'const TREES = '.length, tb + 2))();
const TALENTS = [];
TREES.forEach((tr, i) => tr.t.slice().sort((x, y) => x[1] - y[1] || x[2] - y[2]).forEach(t => TALENTS.push({ name: t[0], tree: i + 1, max: t[3] })));

// settings the fight reads; the page's interface-only fields (iterations, seed) and its selects for consumables are left out
const D = JS.defaults();
for (const f of JS.FIELDS) if (f.g === 'side') delete D[f.k];
delete D.prof1; delete D.prof2; delete D.mode;
const BUFFS = JS.FIELDS.filter(f => f.g === 'buff').map(f => ({ key: f.k, label: f.l.replace(/ \(.*\)$/, '') }));

// the settings a settings code may carry: raid buffs and debuffs, consumables, encounter, rotation options
const short = l => l.replace(/ \(.*\)$/, '');
const SETTINGS = JS.FIELDS.filter(f => ['buff', 'cons', 'tgt', 'rot'].includes(f.g) && f.k !== 'mode')
  .map(f => ({ key: f.k, group: f.g, label: short(f.l), choices: f.t === 'sel' ? Object.fromEntries(f.o.map(o => [o[0], short(o[1])])) : undefined }));

// the effects the fight plays (PROCS on the page), each with the name to show, and the sets that carry one
const cut = (name, open) => { const a = page.indexOf('const ' + name + ' = ' + open), b = page.indexOf('\n', a); return JSON.parse(page.slice(a + name.length + 9, b).replace(/;\s*$/, '')); };
const ITEMS = cut('ITEMS', '['), SETS = cut('SETS', '{'), ENCHANTS = cut('ENCHANTS', '[');
const procLines = [], procSets = [];
for (const k of Object.keys(JS.PROCS)){
  const p = Object.assign({}, JS.PROCS[k]); delete p.r; delete p.x;
  if (/^\d+$/.test(k)) p.n = (ITEMS.find(i => i.id === +k) || { n: 'Item ' + k }).n;
  else if (k[0] === 'e') p.n = (ENCHANTS.find(e => e.e === +k.slice(1)) || { n: 'Enchant ' + k.slice(1) }).n.replace(/^Enchant: /, '');
  else { const [id, pieces] = k.slice(1).split(':'); p.n = SETS[id].n + ' (' + pieces + ')';
    procSets.push({ key: k, pieces: +pieces, name: SETS[id].n, items: '{ ' + ITEMS.filter(i => String(i.set) === id).map(i => '[' + i.id + '] = true').join(', ') + ' }' }); }
  procLines.push('  [' + (/^\d+$/.test(k) ? k : JSON.stringify(k)) + '] = ' + toLua(p) + ',');
}
const setLines = procSets.map(s => '  { key = ' + JSON.stringify(s.key) + ', pieces = ' + s.pieces + ', name = ' + toLua(s.name) + ', items = ' + s.items + ' },');

const data = `-- GENERATED by tools/gen-ret-data.js from the website (ret-sim.html). Do not edit: change the website, then run the script again.
local ADDON, RS = ...
if RS.notPaladin then return end

RS.VERSION = ${toLua(VERSION)}
-- every setting of the fight with the website's default
RS.DEFAULTS = ${toLua(D)}
-- base stats of a level 60 paladin without gear, per race
RS.RACE_BASE = ${toLua(RACE_BASE)}
-- raid buffs and debuffs: the setting's key and its name
RS.BUFFS = ${toLua(BUFFS)}
-- what a settings code may carry: key, group (buff, cons, tgt, rot), name, and for a choice its values with their names
RS.SETTINGS = ${toLua(SETTINGS)}
-- the talents, tree by tree in the order of the website's talent string
RS.TALENTS = ${toLua(TALENTS)}
-- ready builds: talent ranks by name
RS.PRESETS = ${toLua(JS.PRESETS)}
-- the effects of items, weapon enchants ("e" + enchant id) and set bonuses ("s" + set id + ":" + pieces) that the fight plays
RS.PROCS = {
${procLines.join('\n')}
}
-- the sets with such a bonus: how many pieces it takes and the items that count
RS.PROC_SETS = {
${setLines.join('\n')}
}
`;
fs.writeFileSync(path.join(__dirname, '..', 'RetSim', 'Data.lua'), data);

// the self-test: default settings, the Unsealed Wrath build, one fight per rotation
const fights = [];
for (const [i, mode] of ['socSor', 'sorSoc', 'sorFury', 'socOnly', 'sorOnly', 'shock'].entries()) {
  const v = JS.applyTalents(JS.PRESETS.ws, Object.assign({}, D));
  const seed = 1337 * 7919 + i * 104729;
  const r = JS.simulate(JS.derive(v), JS.resolveMode(mode, v.wSpeed), seed, false);
  fights.push({ mode, seed, dps: r.dps, mana: r.mana, swings: r.swings });
}
fs.writeFileSync(path.join(__dirname, '..', 'RetSim', 'Expected.lua'), `-- GENERATED by tools/gen-ret-data.js: fights played by the website's engine, for the self-test (/rsim test).
local ADDON, RS = ...
if RS.notPaladin then return end

RS.EXPECTED = ${toLua(fights)}
`);
console.log('Data.lua: ' + Object.keys(D).length + ' settings, ' + TALENTS.length + ' talents, ' + Object.keys(JS.PRESETS).length + ' builds, version ' + VERSION);
console.log('Expected.lua: ' + fights.map(f => f.mode + ' ' + f.dps.toFixed(2)).join(', '));
